/* ============================================================================
   docs/assets/demo.svg is the tool's own output, not a screenshot: this runs
   the command the README shows and lays the lines out as text in an SVG.

     node --experimental-strip-types scripts/render-demo.ts
   ========================================================================= */

import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const fixture = 'test/fixtures/rules/ELB-KX-001';
const out = mkdtempSync(join(tmpdir(), 'edgepq-demo-'));
let stdout = '';
try {
  stdout = execFileSync(process.execPath, [join(root, 'bin/edgepq.js'), 'scan', fixture, '--out', out], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });
} catch (e) {
  stdout = (e as { stdout: string }).stdout;
}
const lines = stdout.replace(out, './edgepq-out').trimEnd().split('\n');

const width = 960;
const lineHeight = 19;
const top = 56;
const wrap = (s: string, cols = 118): string[] => {
  const outLines: string[] = [];
  let rest = s;
  while (rest.length > cols) { outLines.push(rest.slice(0, cols)); rest = '    ' + rest.slice(cols); }
  outLines.push(rest);
  return outLines;
};
const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const style = (l: string): string => {
  if (/^edgepq \d/.test(l)) return 'fill="#FFFFFF" font-weight="700"';
  if (/^\$ /.test(l)) return 'fill="#8FA6C3"';
  if (/failed \d+/.test(l)) return 'fill="#FF7B72"';
  if (/^  (critical|high)\s/.test(l)) return 'fill="#F5C242"';
  return 'fill="#E6EDF3"';
};
const rows = lines.flatMap((l) => wrap(l));
const svgHeight = top + rows.length * lineHeight + 20;
const text = rows.map((l, i) => `<text x="22" y="${top + i * lineHeight}" xml:space="preserve" ${style(l)}>${esc(l.replace(/\*\*/g, ''))}</text>`).join('\n');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${svgHeight}" width="${width}" height="${svgHeight}" font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace" font-size="12.5">
<!-- Generated by scripts/render-demo.ts from the tool's own output on ${fixture}: edgepq scan ${fixture} -->
<rect width="${width}" height="${svgHeight}" rx="12" fill="#0B2545"/>
<circle cx="22" cy="20" r="6" fill="#FF5F57"/><circle cx="42" cy="20" r="6" fill="#FEBC2E"/><circle cx="62" cy="20" r="6" fill="#28C840"/>
<text x="${width / 2}" y="24" text-anchor="middle" fill="#8FA6C3" font-size="12">edgepq scan ./terraform</text>
${text}
</svg>
`;
writeFileSync(join(root, 'docs/assets/demo.svg'), svg);
console.log(`docs/assets/demo.svg: ${rows.length} lines`);
